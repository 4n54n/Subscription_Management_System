  @SubscribeMessage('update_media_permissions')
  async onUpdateMediaPermissions(
    @ConnectedSocket() _client: Socket,
    @MessageBody()
    payload: {
      roomId: string;
      sessionId: string;
      allowGuestVideo: boolean;
      allowGuestAudio: boolean;
      allowGuestScreenShare: boolean;
      allowTranslation?: boolean;
      allowGuestTranslation?: boolean;
    }
  ) {
    const members = getRoomMembers(payload.roomId);
    const member = members.get(payload.sessionId);
    if (!member?.isHost) return { error: 'Unauthorized' };

    const state = roomStates.get(payload.roomId);
    if (!state) return { error: 'Room not found' };

    const newAllowTranslation =
      payload.allowTranslation !== undefined
        ? payload.allowTranslation
        : (state.mediaPermissions.allowTranslation ?? false);
    const newAllowGuestTranslation =
      payload.allowGuestTranslation !== undefined
        ? payload.allowGuestTranslation
        : (payload.allowTranslation !== undefined
            ? payload.allowTranslation
            : (state.mediaPermissions.allowGuestTranslation ?? newAllowTranslation));

    state.mediaPermissions = {
      allowGuestVideo: payload.allowGuestVideo,
      allowGuestAudio: payload.allowGuestAudio,
      allowGuestScreenShare: payload.allowGuestScreenShare,
      allowTranslation: newAllowTranslation,
      allowGuestTranslation: newAllowGuestTranslation,
    };

    // Save updated permissions to database so rejoin/history popups receive the updated permissions
    try {
      const room = await this.prisma.presentationRoom.findUnique({
        where: { id: payload.roomId },
      });
      if (room) {
        const existingPerms = (room.permissions as any) || {};
        const updatedPerms = {
          ...existingPerms,
          allowVideo: payload.allowGuestVideo,
          allowAudio: payload.allowGuestAudio,
          allowScreenShare: payload.allowGuestScreenShare,
          allowTranslation: newAllowTranslation,
          allowGuestVideo: payload.allowGuestVideo,
          allowGuestAudio: payload.allowGuestAudio,
          allowGuestScreenShare: payload.allowGuestScreenShare,
          allowGuestTranslation: newAllowGuestTranslation,
        };
        await this.prisma.presentationRoom.update({
          where: { id: payload.roomId },
          data: { permissions: updatedPerms as any },
        });
      }
    } catch (err) {
      this.logger.error(
        `Failed to persist updated media permissions for room ${payload.roomId}:`,
        err
      );
    }

    this.server
      .to(payload.roomId)
      .emit('media_permissions_update', state.mediaPermissions);
    return { success: true };
  }

