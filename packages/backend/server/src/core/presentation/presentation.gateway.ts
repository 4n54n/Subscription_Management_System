  @SubscribeMessage('mute_user')
  onMuteUser(
    @ConnectedSocket() _client: Socket,
    @MessageBody()
    payload: {
      roomId: string;
      sessionId: string;
      targetSessionId: string;
      type: 'audio' | 'video' | 'screen';
      muted?: boolean;
    }
  ) {
    const members = getRoomMembers(payload.roomId);
    const member = members.get(payload.sessionId);
    if (!member?.isHost) return { error: 'Unauthorized' };

    const target = members.get(payload.targetSessionId);
    if (!target) return { error: 'Target member not found' };

    let state = roomStates.get(payload.roomId);
    if (!state) {
      state = {
        terminalActive: false,
        browserActive: false,
        browserUrl: '',
        terminalHistory: [],
        mediaPermissions: {
          allowGuestVideo: true,
          allowGuestAudio: true,
          allowGuestScreenShare: false,
        },
        agoraUidMap: new Map(),
        forceMutedTypes: new Set(),
      };
      roomStates.set(payload.roomId, state);
    }

    if (!(state as any).forceMutedUsers) {
      (state as any).forceMutedUsers = new Map();
    }

    let userMutes = (state as any).forceMutedUsers.get(payload.targetSessionId);
    if (!userMutes) {
      userMutes = new Set();
      (state as any).forceMutedUsers.set(payload.targetSessionId, userMutes);
    }

    let nextMuted = payload.muted;
    if (nextMuted === undefined) {
      nextMuted = !userMutes.has(payload.type);
    }

    if (nextMuted) {
      userMutes.add(payload.type);
    } else {
      userMutes.delete(payload.type);
    }

    const targetSocketId = (target as any).__socketId;
    if (targetSocketId) {
      this.server
        .to(targetSocketId)
        .emit('force_mute', { type: payload.type, muted: nextMuted });
    }

    // Broadcast the updated state sync so the host's client UI updates immediately
    this.emitRoomState(payload.roomId, state);

    return { success: true, muted: nextMuted };
  }

  @SubscribeMessage('chat_message')
  async onChatMessage(
    @ConnectedSocket() client: Socket,
    @MessageBody() payload: ChatPayload
  ) {
    const members = getRoomMembers(payload.roomId);
    const member = members.get(payload.sessionId);
    if (!member) {
      return { error: 'Not in room' };
    }

    const room = await this.presentationService.getRoom(payload.roomId);
    const permissions = room.permissions as any;

    const message: ChatMessage = {
      id: `${Date.now()}-${Math.random().toString(36).slice(2)}`,
      sessionId: payload.sessionId,
      name: member.name,
      content: payload.content,
      timestamp: Date.now(),
      replyToSessionId: payload.replyToSessionId,
    };

    // Save to chat history
    const state = roomStates.get(payload.roomId);
    if (state) {
      if (!state.chatHistory) state.chatHistory = [];
      state.chatHistory.push({
        ...message,
        isPrivate:
          (member.isHost && !!payload.replyToSessionId) ||
          (!member.isHost && !!permissions?.privateChat),
        targetSessionId: member.isHost ? payload.replyToSessionId : undefined,
      });
      if (state.chatHistory.length > 500) {
        state.chatHistory.shift();
      }
    }

    // Case 1: Host sending a private reply to a specific attendee
    if (member.isHost && payload.replyToSessionId) {
      client.emit('chat_message', message);
      const targetMember = members.get(payload.replyToSessionId);
      const targetSocketId = (targetMember as any)?.__socketId;
      if (targetSocketId && targetSocketId !== client.id) {
        this.server.to(targetSocketId).emit('chat_message', message);
      }
      return { success: true };
    }

    // Case 2: Attendee sending message in private-only mode
    if (!member.isHost && permissions?.privateChat) {
      client.emit('chat_message', message);
      const hostSocketId = hostSocket.get(payload.roomId);
      if (hostSocketId && hostSocketId !== client.id) {
        this.server.to(hostSocketId).emit('chat_message', message);
      }
      return { success: true };
    }

    // Case 3: Public message (Host default broadcast, or normal public attendee chat)
    this.server.to(payload.roomId).emit('chat_message', message);
    return { success: true };
  }

  @SubscribeMessage('gemini_chat')
  async onGeminiChat(
    @ConnectedSocket() client: Socket,
    @MessageBody() payload: GeminiChatPayload
  ) {
    try {
      const room = await this.presentationService.getRoom(payload.roomId);
      const permissions = room.permissions as any;
      let customApiKey = permissions?.apiKey;

      if (!customApiKey) {
        const setting = await this.prisma.workspaceGeminiSetting.findUnique({
          where: { workspaceId: room.workspaceId },
        });
        if (setting?.apiKey) {
          customApiKey = setting.apiKey;
        }
      }

      if (!customApiKey) {
        const globalConfig = this.serverService.getConfig();
        customApiKey =
          globalConfig.copilot?.providers?.gemini?.apiKey ||
          process.env['GEMINI_API_KEY'] ||
          process.env['GOOGLE_GEMINI_API_KEY'];
      }

      if (!permissions?.allowGemini) {
        client.emit('gemini_reply_chunk', {
          sessionId: payload.sessionId,
          chunk: '',
          done: true,
          disabled: true,
          disabledMessage: 'Disabled by the host',
        });
        return;
      }

      const setting = await this.prisma.workspaceGeminiSetting.findUnique({
        where: { workspaceId: room.workspaceId },
      });

      const globalConfig = this.serverService.getConfig();
      const dbOverrides = this.serverService.getDbOverrides();
      const adminConfigResearchDocModel = (dbOverrides as any)?.copilot?.researchDocModel || globalConfig.copilot?.researchDocModel;
      const adminConfigGeminiModel = (dbOverrides as any)?.copilot?.providers?.gemini?.model || globalConfig.copilot?.providers?.gemini?.model;

      const workspaceDbModel = setting?.meetingModel || setting?.model;

      const modelToUse = (
        workspaceDbModel ||
        adminConfigResearchDocModel ||
        adminConfigGeminiModel ||
        'gemini-2.5-flash'
      ).replace(/^models\//i, '').trim();

      const stream = this.geminiService.chatStream(
        payload.roomId,
        payload.sessionId,
        payload.userMessage,
        modelToUse,
        customApiKey,
        permissions?.limitOutput
      );

      for await (const chunk of stream) {
        client.emit('gemini_reply_chunk', {
          sessionId: payload.sessionId,
          chunk,
          done: false,
        });
      }

      client.emit('gemini_reply_chunk', {
        sessionId: payload.sessionId,
        chunk: '',
        done: true,
      });

      return { success: true };
    } catch (e: any) {
      this.logger.error('gemini_chat error', e);
      client.emit('gemini_reply_chunk', {
        sessionId: payload.sessionId,
        chunk: `AI Service Error: ${e.message}`,
        done: true,
      });
      return { error: e.message };
    }
  }

  /**
   * Called by the REST controller when host ends the room.
   * Notifies all clients and cleans up in-memory state.
   */
  async broadcastRoomEnded(roomId: string) {
    this.server.to(roomId).emit('room_ended', { roomId });
    roomMembers.delete(roomId);
    pendingGuests.delete(roomId);
    hostSocket.delete(roomId);
    approvedSessionIds.delete(roomId);
    kickedSessionIds.delete(roomId);
    this.geminiService.clearRoom(roomId);

    // Clear timers & deactivate terminal first to block auto-reconnection
    const state = roomStates.get(roomId);
    if (state) {
      state.terminalActive = false;
      if (state.promptTimer) clearTimeout(state.promptTimer);
      if (state.safetyTimer) clearTimeout(state.safetyTimer);
    }

    // Clean up terminal process
    const proc = roomTerminals.get(roomId);
    if (proc) {
      try {
        proc.stdin.end();
        proc.kill();
      } catch (_) {}
      roomTerminals.delete(roomId);
      roomTerminalBuffers.delete(roomId);
    }
    roomStates.delete(roomId);

    this.logger.log(`Room ${roomId} ended broadcast sent`);
  }

